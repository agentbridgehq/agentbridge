// Command gendocs writes the client compatibility page from the adapters
// themselves.
//
// Compatibility documentation written by hand goes stale within one release and
// then actively misleads, which for this page would be worse than having none:
// the whole product claim is that we tell people the truth about what each
// client will and will not take. Generating it from the adapters means the page
// cannot disagree with the code, and a test fails when it drifts.
//
// Run with `make docs`.
package main

import (
	"fmt"
	"os"
	"strings"

	"github.com/agentbridge/agentbridge/internal/adapter"
	adapterreg "github.com/agentbridge/agentbridge/internal/adapter/registry"
)

func main() {
	out := Render()
	if err := os.WriteFile("docs/clients.md", []byte(out), 0o644); err != nil {
		fmt.Fprintf(os.Stderr, "gendocs: %v\n", err)
		os.Exit(1)
	}
	fmt.Println("wrote docs/clients.md")
}

// Render builds the page. Exported so the freshness test can compare against it
// without shelling out.
func Render() string {
	var b strings.Builder

	b.WriteString(`# Client compatibility

<!--
Generated by internal/tools/gendocs from the adapters themselves. Run
` + "`make docs`" + ` after changing one. Do not edit by hand — a test compares this
file against the code and will fail.
-->

What each agent client actually takes, and what it does not.

**` + "`native`" + `** the client loads this as-is · **` + "`translated`" + `** we convert it into
the client's own format · **` + "`none`" + `** the client has no such concept ·
**` + "`undocumented`" + `** the client may well support it, but its vendor has not
published where the files go, and we will not write to a path we have not
verified.

| Client | Agent Plugins | Skills | MCP servers | Configuration |
|---|---|---|---|---|
`)

	// A zero Env is enough: this asks each adapter what it *is*, not what is
	// installed on the machine generating the page.
	adapters := adapterreg.Adapters(adapter.Env{})

	for _, a := range adapters {
		c := a.Client()
		conformant := "no"
		if c.Conformant {
			conformant = "yes"
		}
		fmt.Fprintf(&b, "| **%s** | %s | `%s` | `%s` | [docs](%s) |\n",
			c.Name, conformant, c.Skills, c.MCP, c.ConfigDoc)
	}

	b.WriteString(`
## The thing worth noticing

The one client that does **not** implement the standard carries the most, and
three that *do* carry the least. Claude Code is the only target whose plugin
layout its vendor documents, so it is the only one that receives skills at all.

That is not an accident of this implementation. **Conformance is not
documentation.** A client can implement Agent Plugins perfectly and still leave
nobody able to install a plugin into it programmatically, because where a
portable package goes on disk is a separate question that the specification
deliberately does not answer (§6.1 fixes locations *within* a plugin, not where
the plugin itself is installed).

Where a vendor has not published that location, the adapter declines to guess.
Writing into an unverified path on a developer's machine to make a table look
better is not a trade worth making, so those clients get their MCP servers and
an explicit note that their skills were not installed. Measuring the real
locations is what the conformance harness is for.

## What each client may not carry

Every loss below is reported at install time, with the reason. ` + "`by design`" + `
means the client genuinely cannot do it; ` + "`fault`" + ` means something went wrong and
can be fixed.

`)

	for _, a := range adapters {
		c := a.Client()
		fmt.Fprintf(&b, "### %s\n\n", c.Name)
		fmt.Fprintf(&b, "| Kind | Code | Meaning |\n|---|---|---|\n")

		for _, code := range c.Losses {
			info, ok := adapter.LookupLoss(code)
			if !ok {
				continue
			}
			kind := "fault"
			if info.Expected {
				kind = "by design"
			}
			fmt.Fprintf(&b, "| %s | `%s` | %s |\n", kind, info.Code, info.Meaning)
		}
		b.WriteString("\n")
	}

	b.WriteString(`## Adding a client

Adapters implement one interface and declare what they cannot carry. See
[` + "`internal/adapter`" + `](../internal/adapter) — an adapter may not emit a loss code
it has not declared, so a new failure mode has to be catalogued before it can
reach anyone.

## A caution about this page

These are **declared** capabilities, taken from the adapters. They are not
measured against running clients. Until the conformance harness lands, treat
` + "`native`" + ` as "we write what this client's documentation says it reads", not as
"we have watched it work". Where the two differ, the documentation is wrong and
we would like to hear about it.
`)

	return b.String()
}
